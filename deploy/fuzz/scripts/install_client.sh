#!/usr/bin/env bash
# Deploy into a private venv; retain the existing client identity and results.
set -euo pipefail
usage() {
  cat <<'HELP'
Usage: install_client.sh --wheel FILE --cann-root DIR --home DIR [options]
  --python PATH          Python for the new venv (default: python3)
  --runtime-python PATH  Reuse Torch/torch_npu from this existing Python
  --torch-wheel FILE     Install Torch wheel on a fresh environment
  --torch-npu-wheel FILE Install the matching torch_npu wheel
  --nnsmith-wheel FILE  Install a prebuilt fork wheel (offline/local distribution)
  --venv DIR             New venv (default: HOME/deployments/client-WHEEL_SHA256)
  --library-dir DIR      Extra compiler runtime library directory
  --compiler-bin DIR     Compiler executables, when needed by the run package
Creates HOME/client-env.sh and HOME/bin/afx. Does not create/change tokens
or start a campaign. Requires a matching, installed CANN graph-autofusion run package.
HELP
}
PYTHON_BIN=python3; RUNTIME_PYTHON=; TORCH_WHEEL=; NPU_WHEEL=; WHEEL=; CANN_ROOT=; HOME_DIR=; VENV=; LIBRARY_DIR=; COMPILER_BIN=; NNSMITH_WHEEL=
while (($#)); do
  [[ $1 == -h || $1 == --help ]] && { usage; exit 0; }
  (($#>=2)) || { usage >&2; exit 2; }
  case $1 in
    --wheel) WHEEL=$2;; --cann-root) CANN_ROOT=$2;; --home) HOME_DIR=$2;;
    --python) PYTHON_BIN=$2;; --runtime-python) RUNTIME_PYTHON=$2;;
    --torch-wheel) TORCH_WHEEL=$2;; --torch-npu-wheel) NPU_WHEEL=$2;;
    --venv) VENV=$2;; --nnsmith-wheel) NNSMITH_WHEEL=$2;;
    --library-dir) LIBRARY_DIR=$2;; --compiler-bin) COMPILER_BIN=$2;;
    *) echo "Unknown option: $1" >&2; exit 2;;
  esac
  shift 2
done
[[ -f $WHEEL && -f $CANN_ROOT/set_env.sh && -n $HOME_DIR ]] || { usage >&2; exit 2; }
[[ -z $LIBRARY_DIR || -d $LIBRARY_DIR ]] && [[ -z $COMPILER_BIN || -d $COMPILER_BIN ]]
if [[ -z $RUNTIME_PYTHON && ( ! -f $TORCH_WHEEL || ! -f $NPU_WHEEL ) ]]; then
  echo 'Supply --runtime-python, or both --torch-wheel and --torch-npu-wheel.' >&2; exit 2
fi
unset PYTHONPATH PYTHONHOME
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
bash "$SCRIPT_DIR/ensure_sqlite.sh" "$PYTHON_BIN"
umask 077
# CANN environment scripts are not nounset compatible.
set +u; source "$CANN_ROOT/set_env.sh"; set -u
export LD_LIBRARY_PATH="$LIBRARY_DIR${LIBRARY_DIR:+:}${LD_LIBRARY_PATH:-}"
export PATH="$COMPILER_BIN${COMPILER_BIN:+:}$PATH"
WHEEL=$(realpath "$WHEEL"); CANN_ROOT=$(realpath "$CANN_ROOT")
mkdir -p "$HOME_DIR"; HOME_DIR=$(realpath "$HOME_DIR")
DIGEST=$("$PYTHON_BIN" -c 'import hashlib,sys; print(hashlib.sha256(open(sys.argv[1],"rb").read()).hexdigest()[:16])' "$WHEEL")
VENV="${VENV:-$HOME_DIR/deployments/client-$DIGEST}"
[[ ! -e $VENV ]] || { echo "Refusing to overwrite existing venv: $VENV" >&2; exit 1; }
"$PYTHON_BIN" -m venv "$VENV"; VENV=$(realpath "$VENV")
PY="$VENV/bin/python"
"$PY" -m pip install 'pip>=23,<26' 'setuptools==75.8.0' 'wheel==0.45.1'
if [[ -n $RUNTIME_PYTHON ]]; then
  # Append the existing runtime's site-packages, so local pinned dependencies win.
  "$RUNTIME_PYTHON" -I -c 'import site; print("\n".join(site.getsitepackages()))' > "$VENV/runtime-sites.txt"
  "$PY" - "$VENV/runtime-sites.txt" <<'PY'
import site, sys
from pathlib import Path
paths=[p for p in Path(sys.argv[1]).read_text().splitlines() if Path(p).is_dir()]
assert paths, 'No runtime site-packages found'
(Path(site.getsitepackages()[0])/'fuzz-runtime.pth').write_text('\n'.join(paths)+'\n')
PY
else
  "$PY" -m pip install "$TORCH_WHEEL" "$NPU_WHEEL"
fi
"$PY" -m pip install 'decorator' 'attrs' 'psutil' 'scipy' 'packaging'
if [[ -n $NNSMITH_WHEEL ]]; then
  "$PY" -m pip install --ignore-installed "$WHEEL" "$NNSMITH_WHEEL"
else
  "$PY" -m pip install --ignore-installed "$WHEEL[execution]"
fi
# Fail before publishing the new launcher if dependencies or MLIR are incomplete.
(cd / && "$PY" - "$CANN_ROOT" <<'PY'
import json, sys
from pathlib import Path
import torch, torch_npu, autofuse
from autofusex.fuzz.generation.runtime import source_evidence
from autofusex.nnsmith_integration.aten_dialect import validate_runtime
from autofusex.fuzz.backends.mlir_capability import verify_compile_adapter, verify_runtime
from autofusex.fuzz.environment import collect
root=Path(sys.argv[1]).resolve()
assert root in Path(autofuse.__file__).resolve().parents, autofuse.__file__
validate_runtime()
evidence=dict(source_evidence(), compile_adapter=verify_compile_adapter(), codegen=verify_runtime(), environment=collect())
assert root in Path(evidence['codegen']).resolve().parents, evidence['codegen']
print(json.dumps(evidence, ensure_ascii=False))
PY
)
mkdir -p "$HOME_DIR/bin"
ENV_FILE="$HOME_DIR/client-env.sh.tmp"
{
  echo '# Generated by install_client.sh'
  echo 'unset PYTHONPATH PYTHONHOME'
  printf 'source %q\n' "$CANN_ROOT/set_env.sh"
  printf 'export AUTOFUSEX_HOME=%q\n' "$HOME_DIR"
  printf 'export PATH=%q:$PATH\n' "$VENV/bin"
  [[ -z $LIBRARY_DIR ]] || printf 'export LD_LIBRARY_PATH=%q:${LD_LIBRARY_PATH:-}\n' "$LIBRARY_DIR"
  [[ -z $COMPILER_BIN ]] || printf 'export PATH=%q:$PATH\n' "$COMPILER_BIN"
  true
} > "$ENV_FILE"
chmod 600 "$ENV_FILE"; mv "$ENV_FILE" "$HOME_DIR/client-env.sh"
{
  echo '#!/usr/bin/env bash'
  echo 'set -eo pipefail'
  printf 'source %q\n' "$HOME_DIR/client-env.sh"
  printf 'exec %q -m afx "$@"\n' "$PY"
} > "$HOME_DIR/bin/afx.tmp"
chmod 755 "$HOME_DIR/bin/afx.tmp"; mv "$HOME_DIR/bin/afx.tmp" "$HOME_DIR/bin/afx"
echo "Client verified. Launcher: $HOME_DIR/bin/afx"
